/* ---------- health ---------- */
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1 FROM records LIMIT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", database: "unavailable", message: "The database is not responding." });
  }
});

/* ---------- records ---------- */
app.use("/api/records", require("./routes/records"));

/* ---------- unknown routes ---------- */
app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

/* ---------- error handler (four parameters) ---------- */
// eslint-disable-next-line no-unused-vars
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed" || error instanceof SyntaxError) {
    return res.status(400).json({ message: "The request body is not valid JSON." });
  }
  if (error.type === "entity.too.large") {
    return res.status(400).json({ message: "The request body is too large." });
  }
  if (error.status && error.status >= 400 && error.status < 500) {
    return res.status(error.status).json({ message: error.message });
  }
  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Something went wrong on the server. Please try again." });
});

/* ---------- start ---------- */
async function start() {
  try {
    await pool.initDatabase();
    console.log("Database ready.");
  } catch (error) {
    // Keep the server up so /health can report the problem with a 503.
    console.error("Database setup failed:", error.message);
  }
  const port = process.env.PORT || 3000;
  app.listen(port, "0.0.0.0", () => {
    console.log(`Server listening on port ${port}`);
  });
}

start();
